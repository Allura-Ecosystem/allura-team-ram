interface AgentSpec {
  name: string;
  description: string;
  persona: string;
  category: string;
  model: string;
  tools: string[];
  skills: string[];
  taskType: string;
}

/**
 * Infer an agent specification from a coverage gap pattern.
 */
function inferAgentSpec(taskType: string, patterns: SonaPattern[]): AgentSpec {
  // Analyze what existing agents struggled with
  const failurePatterns = patterns.filter((p) => p.type === "repeated_failure");
  const hasPerformanceIssues = patterns.some((p) => p.type === "duration_outlier");

  // Determine appropriate model based on task complexity
  const model = hasPerformanceIssues ? "haiku" : "sonnet";

  // Determine tools based on task type keywords
  const tools = ["Read", "Grep", "Glob"];
  if (taskType.includes("implement") || taskType.includes("build") || taskType.includes("code")) {
    tools.push("Edit", "Write", "Bash");
  }
  if (taskType.includes("test") || taskType.includes("validate")) {
    tools.push("Bash");
  }
  if (taskType.includes("discover") || taskType.includes("recon") || taskType.includes("search")) {
    tools.push("Bash", "Agent");
  }

  // Generate agent name from task type
  const name = taskType
    .replace(/^harness\./, "")
    .replace(/\./g, "-")
    .replace(/[^a-z0-9-]/g, "");

  return {
    name: `${name}-specialist`,
    description: `Specialist agent for ${taskType} — auto-proposed by Genesis Engine due to coverage gap`,
    persona: `${name.charAt(0).toUpperCase() + name.slice(1)} Specialist`,
    category: "Generated",
    model,
    tools,
    skills: ["allura-memory-skill"],
    taskType,
  };
}

