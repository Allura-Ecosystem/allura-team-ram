/**
 * Propose a new agent based on a coverage gap pattern.
 */
export function proposeNewAgent(
  taskType: string,
  patterns: SonaPattern[],
): { spec: AgentSpec; definition: string; proposalId: number | null } {
  const spec = inferAgentSpec(taskType, patterns);
  const definition = generateAgentDefinition(spec);

  // Submit to curator queue
  const gapPattern = patterns.find((p) => p.type === "coverage_gap");
  const result = submitAgentProposal(
    spec.name,
    taskType,
    `Coverage gap: no agent handles ${taskType} well`,
    {
      patterns: patterns.map((p) => ({
        type: p.type,
        description: p.description,
        confidence: p.confidence,
      })),
      inferredSpec: spec,
    },
    gapPattern?.confidence || 0.7,
  );

  const proposalId = "error" in result ? null : result.id;

  console.log(
    `[Genesis] Proposed agent "${spec.name}" for ${taskType}` +
      (proposalId ? ` — curator proposal #${proposalId}` : " — rejected (max proposals reached)"),
  );

  return { spec, definition, proposalId };
}

/**
 * Deploy an approved agent — write the definition file to .opencode/agent/
 */
export async function deployAgent(spec: AgentSpec): Promise<{ path: string; success: boolean }> {
  const definition = generateAgentDefinition(spec);
  const path = `.opencode/agent/${spec.name}.md`;

  try {
    await Bun.write(path, definition);
    console.log(`[Genesis] Agent deployed: ${path}`);
    return { path, success: true };
  } catch (error: any) {
    console.error(`[Genesis] Failed to deploy agent: ${error.message}`);
    return { path, success: false };
  }
}
